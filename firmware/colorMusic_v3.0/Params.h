#pragma once
// Реестр параметров. У каждого параметра постоянный номер ("адрес"), по нему параметр
// читается и меняется извне (см. Control.h). Все значения int16_t, дробные хранятся
// в фиксированной точке (сотые / десятые - см. комментарии).
// Границы и значения по умолчанию - таблица paramMeta[] в .ino.
// Новые параметры добавлять ТОЛЬКО в конец, перед P_COUNT, чтобы не сдвигать номера.
// Список параметров и режимов продублирован в web/index.html - при изменениях обнови и его.

enum ParamId : uint8_t {
  // ----- система
  P_MODE,             // 0  текущий режим, 0.. MODE_COUNT-1
  P_POWER,            // 1  0 - выключено, 1 - включено
  P_BRIGHTNESS,       // 2  общая яркость 0.. 255
  P_EMPTY_BRIGHT,     // 3  яркость "не горящих" светодиодов 0.. 255
  P_LOW_PASS,         // 4  нижний порог шумов режима VU 0.. 1023
  P_SPEKTR_LOW_PASS,  // 5  нижний порог шумов режима спектра 0.. 255
  // ----- шкала громкости
  P_SMOOTH,           // 6  плавность анимации VU, сотые
  P_RAINBOW_STEP,     // 7  шаг радуги VU, десятые
  // ----- цветомузыка, бегущие частоты
  P_SMOOTH_FREQ,      // 8  плавность анимации частот, сотые
  P_MAX_COEF_FREQ,    // 9  порог "вспышки", десятые
  P_FREQ_STROBE_MODE, // 10 подрежим: 0 - все частоты, 1 - высокие, 2 - средние, 3 - низкие
  // ----- огонь
  P_FIRE_HUE,         // 11 цвет огня: 0 красный, 80 зелёный, 140 молния, 190 розовый
  P_FIRE_SPEED,       // 12 скорость движения пламени
  // ----- подсветка
  P_LIGHT_MODE,       // 13 подрежим: 0 - цвет, 1 - смена цвета, 2 - радуга
  P_LIGHT_COLOR,      // 14 цвет подсветки 0.. 255
  P_LIGHT_SAT,        // 15 насыщенность подсветки 0.. 255
  P_COLOR_SPEED,      // 16 период смены цвета, мс
  P_RAINBOW_PERIOD,   // 17 скорость и направление радуги
  P_RAINBOW_STEP_2,   // 18 шаг радуги подсветки, десятые
  // ----- бегущие частоты
  P_RUNNING_SPEED,    // 19 период сдвига, мс
  // ----- анализатор спектра
  P_HUE_START,        // 20 начальный цвет
  P_HUE_STEP,         // 21 шаг цвета
  // ----- огонь
  P_FIRE_SCALE,       // 22 масштаб пламени (шаг шума между светодиодами)

  P_COUNT
};

struct ParamMeta {
  int16_t min, max, def;
};

int16_t paramValues[P_COUNT];

inline int16_t param(uint8_t id) {
  return paramValues[id];
}

// перевод дробных настроек в фиксированную точку
#define FIX10(x) ((int16_t)((x) * 10 + 0.5))
#define FIX100(x) ((int16_t)((x) * 100 + 0.5))
